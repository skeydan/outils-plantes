"""Write site/microscope/js/specimens.js from manifest.json and build.json.

    python3 -I scripts/microscope/make_data.py scripts/microscope/manifest.json site/microscope/img/build.json site/microscope/js/specimens.js

Also writes a small thumbnail of each photograph next to the images (used
for the specimen buttons and the overview map, never as a simulated view). The text fields (names, preparation, scale notes, credits)
come from the manifest; sizes and pixel scales from the build.
"""
import json
import os
import sys

from PIL import Image

KEEP = ['id', 'name', 'kind', 'taxon', 'prep', 'scaleNote', 'takenWith', 'structures', 'na_src']
PHOTO = ['title', 'page', 'author', 'licence', 'licenceUrl', 'about', 'original', 'sha256']


def main(manifest_path, build_path, out_path):
    manifest = json.load(open(manifest_path, encoding='utf-8'))
    build = {b['id']: b for b in json.load(open(build_path, encoding='utf-8'))}
    imgdir = os.path.dirname(build_path)
    out = []
    for sp in manifest['specimens']:
        b = build[sp['id']]
        views = {k: {kk: v[kk] for kk in ('file', 'um_per_px', 'w', 'h')} for k, v in b['views'].items()}
        im = Image.open(os.path.join(imgdir, views['photo']['file']))
        im.thumbnail((360, 360), Image.LANCZOS)
        thumb = f"{sp['id']}-thumb.jpg"
        im.convert('RGB').save(os.path.join(imgdir, thumb), 'JPEG', quality=82, optimize=True)
        d = {k: sp[k] for k in KEEP if k in sp}
        d['photo'] = {k: sp['photo'][k] for k in PHOTO if k in sp['photo']}
        d['size_um'] = b['size_um']
        d['views'] = views
        d['thumb'] = thumb
        out.append(d)
    with open(out_path, 'w', encoding='utf-8') as f:
        f.write('// Specimens of the simulated microscope. Generated by scripts/microscope/make_data.py\n')
        f.write('// from scripts/microscope/manifest.json (texts, credits, scale) and the image build.\n')
        f.write('export const SPECIMENS = [\n')
        for d in out:
            f.write(' ' + json.dumps(d, ensure_ascii=False) + ',\n')
        f.write('];\n')


if __name__ == '__main__':
    if len(sys.argv) != 4:
        raise SystemExit(__doc__)
    main(*sys.argv[1:])
